-- ============================================================
-- 电商平台销售与用户行为分析 · 漏斗分析（SQL 版）
-- 数据库：ecommerce_analysis
-- 说明：按订单状态拆出「下单 → 支付 → 完成」三步漏斗，
--       找转化率最低、流失最严重的一步
-- 口径：下单 = 全部订单；支付 = 已支付 + 已退款（退款也是先付了钱）；
--       完成 = 已支付（付了钱且未退款）
-- ============================================================

SELECT
    下单量,
    支付量,
    完成量,
    ROUND(支付量 / 下单量 * 100, 2) AS 支付转化率_pct,   -- 下单的人里，多少付了钱
    ROUND(完成量 / 支付量 * 100, 2) AS 完成率_pct        -- 付钱的人里，多少没退
FROM (
    SELECT
        COUNT(*)                                                        AS 下单量,   -- 所有订单都算"下过单"
        SUM(CASE WHEN status IN ('已支付', '已退款') THEN 1 ELSE 0 END)  AS 支付量,   -- 付过钱（退款也是先付了钱）
        SUM(CASE WHEN status = '已支付' THEN 1 ELSE 0 END)               AS 完成量    -- 付了钱且没退
    FROM orders_clean
) AS t;

-- 结果：
--   下单量 55000 -> 支付量 46150 -> 完成量 43504
--   支付转化率 83.91%，完成率 94.27%
-- 结论：流失最严重的是第一步「下单→支付」（流失 16.09%），
--       其中"待支付"6017 单意向明确、最容易催付挽回；
--       第二步退款率仅 5.73%，健康。
